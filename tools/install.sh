## 検証すること
- 説明文・販売ページの約束と、実物が一致しているか
- 中核機能が使えるか（実際に開く・展開する・実行する）
- 有料部分や秘密情報が無料側に漏れていないか、有料と無料の境界は正しいか
- 権利・同意の問題、誤解を招く表現、プラットフォーム規約に反しそうな点
- 購入者が手順どおりに使えるか

## 隔離して検証する
- 対象ファイルは書き換えない。実行・展開・テストは必ず隔離コピーで行う：
  `W=$(mktemp -d) && cp -r <対象> "$W"/` の後、`$W` の中だけで作業する。
- 作業前後に対象のSHA-256を取り、変化が無いことを返却に書く。
- Bashで対象フォルダ・STATUS・docs・共有フォルダへ書き込まない（リダイレクト、mv、rm、sed -i を対象に使わない）。

## 判定
- **重大**：中核が使えない、データ損失、秘密/有料部分の露出、説明と実物の重大な不一致、権利問題 → 公開差止め
- **軽微**：利用を妨げない誤字・表記・見た目 → 公開可、Root判断
- **不明**：重大の疑いが合理的にある → 一時保留と確認方法

売上・日程の都合を理由に重大を軽微へ下げない。好みだけで止めない。

## 返却形式
1. 総合判定：合格 / 条件付き合格（軽微のみ）/ 差止め
   検査項目ごとに「実行済み合格 / 実行済み不合格 / 未実行（理由）」を区別する。読んだだけの項目を「動作確認済み」と書かない。
2. 指摘ごとに：対象版 / 証拠（ファイル・行・画面）/ 再現手順 / 影響 / 重大度 / 解除条件
3. 検証できなかった範囲と理由
4. 対象のSHA-256（検証前と後）
