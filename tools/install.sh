- 価格×件数：手取りと、CLAUDE.md の目標金額まで必要な件数を書き、その件数が根拠のある範囲かを確かめる。
- 制作の作り込みや品質の反復は、G1〜G8 に合格した後にだけ行う。

## 進め方
1. **問題探索（マーケティング部）**：商品案ではなく、「お金を払って解決されている問題」を、支払いの証拠（実在の依頼・購入レビュー・有料相談の質問文）から集める。G1・G2 の材料。
2. **企画（企画部）**：問題ごとに、自社が提供できる最小の解決策と、G3〜G7 の評価。推奨の前に、推奨案を止める根拠を3つ以上探して同じ分量で書く。
3. **反証（別セッションの担当）**：推奨案を作っていない担当が、G1〜G8 の観点で「出すべきでない理由」を書く。企画の結論を読む前に、まず自分で証拠を当たる。
4. **Root審査**：G1〜G8 の表で判定。各部の結論を統合する前に、食い違いと [推測] の欄を一覧にする。全案却下も可。
5. **作る前の需要確認（G7）**：合格した案だけ、最小コストで反応を測る。合格ラインを越えたら制作へ。

## 小規模な市場検証の枠
上の G1〜G8 は、大きな投資をする企画の基準として残す。次の条件をすべて満たす小さな商品は、G1〜G8 を全部そろえなくても、最低限の品質と安全性を確保したうえで市場に出して検証する。
- 追加の費用が0円。
- Ownerの作業は、承認を除いて合計1時間以内。
- 撤回できる（出品の停止・非公開・返金で元に戻せる）。
- 法令違反、利用規約違反、個人情報の漏えい、データ破損のリスクがない（ここは品質管理の重大差止めの対象のまま）。
- **検証する価値がある**：買い手がその販路で実際に探している、または依頼を出している証拠が1件以上ある。

